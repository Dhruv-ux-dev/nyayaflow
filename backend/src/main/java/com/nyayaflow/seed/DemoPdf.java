package com.nyayaflow.seed;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Writes a minimal single-page PDF so demo documents are real, downloadable files. Only the seeder
 * uses it; uploaded documents are stored exactly as received.
 */
final class DemoPdf {

    private static final int WRAP = 88;

    private DemoPdf() {
    }

    static byte[] render(String courtName, String caseLine, String title, List<String> paragraphs) {
        StringBuilder content = new StringBuilder();
        content.append("BT /F1 9 Tf 56 800 Td (").append(escape(courtName.toUpperCase())).append(") Tj ET\n");
        content.append("BT /F1 9 Tf 56 786 Td (").append(escape(caseLine)).append(") Tj ET\n");
        content.append("0.6 w 56 776 m 539 776 l S\n");
        content.append("BT /F2 15 Tf 56 748 Td (").append(escape(title)).append(") Tj ET\n");
        content.append("BT /F1 10.5 Tf 56 720 Td 15 TL\n");
        int lines = 0;
        for (String paragraph : paragraphs) {
            for (String line : wrap(paragraph)) {
                if (lines++ > 38) {
                    break;
                }
                content.append('(').append(escape(line)).append(") Tj T*\n");
            }
            content.append("T*\n");
        }
        content.append("ET\n");
        content.append("BT /F1 8 Tf 56 40 Td (")
                .append(escape("Generated by NyayaFlow demo data. Fictional parties and facts - not a real court record."))
                .append(") Tj ET\n");

        byte[] stream = content.toString().getBytes(StandardCharsets.ISO_8859_1);
        List<String> objects = List.of(
                "<< /Type /Catalog /Pages 2 0 R >>",
                "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
                "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
                        + "/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
                "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
                "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>");

        ByteArrayOutputStream out = new ByteArrayOutputStream();
        List<Integer> offsets = new ArrayList<>();
        write(out, "%PDF-1.4\n");
        for (int i = 0; i < objects.size(); i++) {
            offsets.add(out.size());
            write(out, (i + 1) + " 0 obj\n" + objects.get(i) + "\nendobj\n");
        }
        offsets.add(out.size());
        write(out, "6 0 obj\n<< /Length " + stream.length + " >>\nstream\n");
        out.writeBytes(stream);
        write(out, "endstream\nendobj\n");

        int xref = out.size();
        StringBuilder table = new StringBuilder("xref\n0 7\n0000000000 65535 f \n");
        offsets.forEach(offset -> table.append("%010d 00000 n \n".formatted(offset)));
        table.append("trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n").append(xref).append("\n%%EOF\n");
        write(out, table.toString());
        return out.toByteArray();
    }

    private static List<String> wrap(String paragraph) {
        List<String> lines = new ArrayList<>();
        StringBuilder line = new StringBuilder();
        for (String word : paragraph.split("\\s+")) {
            if (line.length() + word.length() + 1 > WRAP && !line.isEmpty()) {
                lines.add(line.toString());
                line.setLength(0);
            }
            if (!line.isEmpty()) {
                line.append(' ');
            }
            line.append(word);
        }
        if (!line.isEmpty()) {
            lines.add(line.toString());
        }
        return lines;
    }

    /** Keeps text within the PDF standard fonts' character set and escapes PDF string syntax. */
    private static String escape(String text) {
        String ascii = text.replace("₹", "Rs. ").replace('“', '"').replace('”', '"').replace('’', '\'')
                .replace("—", "-").replace("–", "-").replace("…", "...");
        StringBuilder escaped = new StringBuilder();
        for (char c : ascii.toCharArray()) {
            if (c == '(' || c == ')' || c == '\\') {
                escaped.append('\\').append(c);
            } else if (c >= 32 && c < 127) {
                escaped.append(c);
            } else {
                escaped.append('?');
            }
        }
        return escaped.toString();
    }

    private static void write(ByteArrayOutputStream out, String text) {
        out.writeBytes(text.getBytes(StandardCharsets.ISO_8859_1));
    }
}
